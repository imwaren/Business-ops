-- Staging table for Xero SOA CSVs on mytemr_master_uat.
-- Recreate is intentional: LOAD DATA is the source of truth.

DROP TABLE IF EXISTS soa_dump;

CREATE TABLE soa_dump (
  id INT(11) NOT NULL AUTO_INCREMENT,
  source_file VARCHAR(255) DEFAULT NULL,
  ContactName VARCHAR(255) DEFAULT NULL,
  EmailAddress VARCHAR(255) DEFAULT NULL,
  POAddressLine1 VARCHAR(255) DEFAULT NULL,
  POAddressLine2 VARCHAR(255) DEFAULT NULL,
  POAddressLine3 VARCHAR(255) DEFAULT NULL,
  POAddressLine4 VARCHAR(255) DEFAULT NULL,
  POCity VARCHAR(255) DEFAULT NULL,
  PORegion VARCHAR(255) DEFAULT NULL,
  POPostalCode VARCHAR(255) DEFAULT NULL,
  POCountry VARCHAR(255) DEFAULT NULL,
  SAAddressLine1 VARCHAR(255) DEFAULT NULL,
  SAAddressLine2 VARCHAR(255) DEFAULT NULL,
  SAAddressLine3 VARCHAR(255) DEFAULT NULL,
  SAAddressLine4 VARCHAR(255) DEFAULT NULL,
  SACity VARCHAR(255) DEFAULT NULL,
  SARegion VARCHAR(255) DEFAULT NULL,
  SAPostalCode VARCHAR(255) DEFAULT NULL,
  SACountry VARCHAR(255) DEFAULT NULL,
  InvoiceNumber VARCHAR(255) DEFAULT NULL,
  Reference VARCHAR(255) DEFAULT NULL,
  InvoiceDate VARCHAR(255) DEFAULT NULL,
  DueDate VARCHAR(255) DEFAULT NULL,
  PlannedDate VARCHAR(255) DEFAULT NULL,
  Total VARCHAR(255) DEFAULT NULL,
  TaxTotal VARCHAR(255) DEFAULT NULL,
  InvoiceAmountPaid VARCHAR(255) DEFAULT NULL,
  InvoiceAmountDue VARCHAR(255) DEFAULT NULL,
  InventoryItemCode VARCHAR(255) DEFAULT NULL,
  Description TEXT DEFAULT NULL,
  Quantity VARCHAR(255) DEFAULT NULL,
  UnitAmount VARCHAR(255) DEFAULT NULL,
  Discount VARCHAR(255) DEFAULT NULL,
  LineAmount VARCHAR(255) DEFAULT NULL,
  AccountCode VARCHAR(255) DEFAULT NULL,
  TaxType VARCHAR(255) DEFAULT NULL,
  TaxAmount VARCHAR(255) DEFAULT NULL,
  TrackingName1 VARCHAR(255) DEFAULT NULL,
  TrackingOption1 VARCHAR(255) DEFAULT NULL,
  TrackingName2 VARCHAR(255) DEFAULT NULL,
  TrackingOption2 VARCHAR(255) DEFAULT NULL,
  Currency VARCHAR(255) DEFAULT NULL,
  Type VARCHAR(255) DEFAULT NULL,
  Sent VARCHAR(255) DEFAULT NULL,
  Status VARCHAR(255) DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_soa_invoice (InvoiceNumber),
  KEY idx_soa_contact (ContactName),
  KEY idx_soa_type (Type),
  KEY idx_soa_status (Status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
