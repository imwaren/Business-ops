"""Embed canonical master posting definitions without replacing unrelated helpers."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
posting = (OUT / 'posting.sql').read_text()
schema = (OUT / 'schema.sql').read_text()
marker = '-- BEGIN SHARED FUND ACCOUNTING (generated by sql/shared_funds/build.py)'
for suffix in ['', '_uat']:
    target = ROOT / f'sql/general_ledger_triggers_master{suffix}.sql'
    source = target.read_text()
    prefix = source.split(marker)[0].rstrip()
    # Later additive releases are preserved verbatim, including refund support.
    tail = source[source.index('-- BEGIN MASTER REFUND APV ENUM SUPPORT'):] if '-- BEGIN MASTER REFUND APV ENUM SUPPORT' in source else ''
    target.write_text(prefix + '\n\n' + marker + '\n' + schema + '\n' + posting + '\n' + tail)
(OUT / 'install.sql').write_text('-- Generated by build.py. Master only; no backfill.\n'
    + (OUT / 'assert.sql').read_text() + '\n' + schema + '\n' + posting)
rollback = ['-- Restore exact prior definitions after removing release definitions; retain additive schema.']
for kind in ['TRIGGER', 'PROCEDURE', 'FUNCTION']:
    for name in re.findall(r'CREATE ' + kind + r'(?: IF NOT EXISTS)? (\w+)', posting):
        rollback.append(f'DROP {kind} IF EXISTS {name};')
(OUT / 'rollback.sql').write_text('\n'.join(rollback) + '\n')
