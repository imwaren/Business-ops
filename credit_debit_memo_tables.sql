CREATE TABLE `credit_memo` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `control_no` varchar(50) DEFAULT NULL,
  `billing_id` int(11) NOT NULL,
  `branch_id` int(11) NOT NULL,
  `debit_account_type_id` int(11) NOT NULL,
  `credit_account_type_id` int(11) NOT NULL,
  `date_issued` date NOT NULL,
  `reason` varchar(255) NOT NULL,
  `amount` decimal(13,2) NOT NULL DEFAULT 0.00,
  `remarks` text DEFAULT NULL,
  `status` enum('pending','approved','disapproved') NOT NULL DEFAULT 'pending',
  `approved_by` int(11) DEFAULT NULL,
  `approved_on` datetime DEFAULT NULL,
  `disapproved_by` int(11) DEFAULT NULL,
  `disapproved_on` datetime DEFAULT NULL,
  `added_by` int(11) NOT NULL,
  `added_on` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_by` int(11) DEFAULT NULL,
  `updated_on` timestamp NULL DEFAULT NULL ON UPDATE current_timestamp(),
  `is_deleted` tinyint(1) DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `control_no` (`control_no`),
  KEY `billing_id` (`billing_id`),
  KEY `branch_id` (`branch_id`),
  KEY `status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

